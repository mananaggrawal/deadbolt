// Build step (after `python3 ../game/build.py site`):
//  - static files Vercel's CDN serves from public/: the voices, three.js, app icons
//  - src/generated/assets.js: what the server function needs bundled in (page templates,
//    the room list, art and fonts for preview cards), so nothing is read from disk at runtime
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const gameDist = path.resolve(site, process.env.GAME_DIR || '../game/dist/site');
const pub = path.join(site, 'public');
const rel = p => path.relative(site, p);

const rooms = JSON.parse(fs.readFileSync(path.join(gameDist, 'rooms.json'), 'utf8'));

// game code and voices: public/game/app.<hash>.js, public/game/vo.<hash>.json (old hashes removed)
fs.mkdirSync(path.join(pub, 'game'), { recursive: true });
const keep = [rooms.app, rooms.vo];
for (const f of fs.readdirSync(path.join(pub, 'game'))) if (!keep.includes(f)) fs.rmSync(path.join(pub, 'game', f));
for (const f of keep) fs.copyFileSync(path.join(gameDist, f), path.join(pub, 'game', f));

// three.js
fs.mkdirSync(path.join(pub, 'vendor'), { recursive: true });
fs.copyFileSync(path.join(site, 'node_modules/three/build/three.module.js'), path.join(pub, 'vendor/three-0.160.0.module.js'));

// icons, all the white door logo: favicon.ico (16, 32 and 48 px, for browsers and search results that
// don't take the SVG) from the rounded favicon; the home-screen and app icons from the full-bleed icon.svg
const pngOf = (file, s) => new Resvg(fs.readFileSync(path.join(pub, file)), { fitTo: { mode: 'width', value: s } }).render().asPng();
for (const s of [192, 512]) fs.writeFileSync(path.join(pub, `icon-${s}.png`), pngOf('icon.svg', s));
fs.writeFileSync(path.join(pub, 'apple-touch-icon.png'), pngOf('icon.svg', 180));
fs.writeFileSync(path.join(pub, 'favicon.ico'), ico([16, 32, 48].map(s => [s, pngOf('favicon.svg', s)])));
// an .ico holding PNG images: a 6-byte header, a 16-byte entry per image, then the images
function ico(images) {
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(images.length, 4);
  let offset = head.length;
  images.forEach(([s, png], i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(s % 256, e); head.writeUInt8(s % 256, e + 1);   // width, height (0 means 256)
    head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6);     // colour planes, bits per pixel
    head.writeUInt32LE(png.length, e + 8); head.writeUInt32LE(offset, e + 12);
    offset += png.length;
  });
  return Buffer.concat([head, ...images.map(([, png]) => png)]);
}

// everything the function needs, as one module
const b64 = f => fs.readFileSync(f).toString('base64');
const art = {};
for (const f of fs.readdirSync(path.join(pub, 'art'))) if (f.endsWith('.jpg')) art[f.replace(/\.jpg$/, '')] = b64(path.join(pub, 'art', f));
const fontDir = path.join(site, 'node_modules/@fontsource/geist-sans/files');
const fonts = Object.fromEntries([400, 500, 600].map(w => [w, b64(path.join(fontDir, `geist-sans-latin-${w}-normal.woff`))]));
const out = [
  '// Generated by tools/prepare.mjs. Do not edit; run `npm run build`.',
  `export const landingHtml = ${JSON.stringify(fs.readFileSync(path.join(site, 'templates/landing.html'), 'utf8'))};`,
  `export const playHtml = ${JSON.stringify(fs.readFileSync(path.join(gameDist, 'play.html'), 'utf8').replace(/<title>[^<]*<\/title>\n?/, ''))};`,
  `export const rooms = ${JSON.stringify(rooms)};`,
  `export const art = ${JSON.stringify(art)};`,
  `export const fonts = ${JSON.stringify(fonts)};`,
  '',
].join('\n');
fs.mkdirSync(path.join(site, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(site, 'src/generated/assets.js'), out);
console.log(`prepared public/game/${rooms.app}, ${rooms.vo}, public/vendor, icons, src/generated/assets.js (${(out.length / 1e6).toFixed(1)} MB, ${rooms.mysteries.length} rooms)`);
